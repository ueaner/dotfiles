-- Panel UI
---------------------------------------------------------------------------

-- 面板 HTML 放在同目录的 clipboard.html
local function readHtml()
  local dir = debug.getinfo(1, "S").source:match("^@(.*/)") or (hs.configdir .. "/")
  local f = assert(io.open(dir .. "clipboard.html", "r"), "clipboard.html not found in " .. dir)
  local content = f:read("a")
  f:close()
  return content
end

-- 文本的预览片段和统计信息，按条目缓存（text 不会变）
local function textMeta(item)
  if item.meta then return item.meta end
  local text = item.text
  local preview, truncated = text, false
  if #text > M.previewChars then -- 字节数 <= 字符上限时不可能超出
    local ok, pos = pcall(utf8.offset, text, M.previewChars + 1)
    if ok and pos and pos <= #text then
      preview, truncated = text:sub(1, pos - 1), true
    elseif not ok then -- 非法 UTF-8，按字节截
      preview, truncated = text:sub(1, M.previewChars), true
    end
  end
  item.meta = {
    preview = preview,
    truncated = truncated,
    len = utf8.len(text) or #text,
    lines = select(2, text:gsub("\n", "")) + 1,
  }
  return item.meta
end

local function payload()
  local list = {}
  for _, item in ipairs(history) do
    local time = os.date("%m-%d %H:%M", item.time)
    if item.type == "text" then
      local meta = textMeta(item)
      table.insert(list, {
        id = item.id,
        type = "text",
        text = meta.preview,
        truncated = meta.truncated,
        len = meta.len,
        lines = meta.lines,
        time = time,
      })
    else
      table.insert(list, { id = item.id, type = "image", url = item.thumb, size = item.size, time = time })
    end
  end
  return list
end

-- 把最新的 history 同步进 webview（隐藏状态下也会执行，保证下次打开时已是最新）
-- 只更新数据，保留当前搜索词和选中项；打开面板时由 prepare() 重置
function refresh()
  if not webview then return end
  webview:evaluateJavaScript("update(" .. hs.json.encode(payload()) .. ")")
end

local revealTimer

-- 窗口已以 alpha 0 显示且新内容已绘制，淡入并聚焦
local function reveal()
  if revealTimer then
    revealTimer:stop()
    revealTimer = nil
  end
  if not webview:isVisible() or webview:alpha() == 1 then return end
  webview:alpha(1)
  hs.focus()
  webview:hswindow():focus()
end

local function hide(restoreFocus)
  if webview and webview:isVisible() then
    webview:alpha(0):hide()
  end
  if restoreFocus then
    if lastWindow then
      lastWindow:focus()
    elseif lastApp then
      lastApp:activate()
    end
  end
end

local function paste(id)
  local index, item = findById(id)
  hide(true)
  if not item then return end
  if item.type == "text" then
    hs.pasteboard.setContents(item.text)
  else
    hs.pasteboard.writeObjects(item.image)
  end
  selfChangeCount = hs.pasteboard.changeCount()

  -- 立即移到最前并刷新时间，不等 watcher 轮询
  table.remove(history, index)
  item.time = os.time()
  table.insert(history, 1, item)
  save()
  refresh()
  if M.autoPaste then
    hs.timer.doAfter(0.08, function()
      hs.eventtap.keyStroke({ "cmd" }, "v", 0)
    end)
  end
end

local function onMessage(msg)
  local body = msg.body
  if body.action == "select" then
    paste(body.id)
  elseif body.action == "delete" then
    local index = findById(body.id)
    if index then
      table.remove(history, index)
      save()
      refresh()
    end
  elseif body.action == "close" then
    hide(true)
  elseif body.action == "ready" then
    reveal()
  end
end

local function createWebview()
  local controller = hs.webview.usercontent.new("clipboard"):setCallback(onMessage)
  webview = hs.webview.new({ x = 0, y = 0, w = M.width, h = M.height }, { developerExtrasEnabled = false }, controller)
    :windowStyle({ "borderless" })
    :transparent(true)
    :shadow(true)
    :allowTextEntry(true)
    :level(hs.drawing.windowLevels.modalPanel)
    :behavior(hs.drawing.windowBehaviors.moveToActiveSpace)
    :windowCallback(function(action, _, state)
      -- 点击面板外部（失去焦点）时自动关闭
      if action == "focusChange" and state == false then
        hide(false)
      end
    end)
    :alpha(0)
    :html(readHtml())
end

function M.show()
  if webview:isVisible() then
    hide(true)
    return
  end
  if prune() then save() end
  lastWindow = hs.window.focusedWindow()
  lastApp = hs.application.frontmostApplication()
  local screen = (lastWindow and lastWindow:screen() or hs.screen.mainScreen()):frame()
  webview:topLeft({
    x = screen.x + (screen.w - M.width) / 2,
    y = screen.y + screen.h * 0.22,
  })
  -- 先以 alpha 0 显示让 WebKit 能重绘，画完新列表后由页面发 ready 再 reveal()
  webview:alpha(0):show()
  webview:evaluateJavaScript("prepare(" .. hs.json.encode(payload()) .. ")")
  -- 兜底：页面没回 ready 也在 300ms 后显示
  revealTimer = hs.timer.doAfter(0.3, reveal)
end

function M.clear()
  history = {}
  save()
  refresh()
  hs.alert.show("Clipboard history cleared")
end

function M.start()
  load()
  createWebview()
  watcher = hs.pasteboard.watcher.new(onChange) -- new() 即开始监听（每 0.5s 检查一次）
  return M
end

function M.stop()
  if watcher then watcher:stop() end
  if webview then webview:delete() end
end

return M
