-- 剪切板历史管理：只用 Hammerspoon 自带模块
--   hs.pasteboard.watcher  监听剪切板变化
--   hs.webview             自绘 Spotlight 风格的选择面板（跟随系统 Appearance：Light/Dark，界面在 clipboard.html）
--   hs.settings            持久化文本历史（重启 Hammerspoon 后保留；图片只在内存中）
--
-- 用法（init.lua）：
--   local clipboard = require("clipboard").start()
--   hs.hotkey.bind({ "cmd" }, ";", clipboard.show)
--
-- 面板快捷键：↑/↓ 或 ⌃P/⌃N 移动，↩ 复制（M.autoPaste=true 时直接粘贴），⌘⌫ 删除当前条目，Esc 关闭

local M = {}

M.maxItems = 200 -- 最多保存条数（文本 + 图片）
M.maxImages = 20 -- 其中最多保存的图片数
M.maxTextSize = 256 * 1024 -- 单条文本超过这个字节数就不记录
M.maxAge = 7 * 24 * 3600 -- 超过这个秒数的条目自动清理；nil 表示不按时间清理
M.previewChars = 2000 -- 面板里只传前 N 个字符用于列表/预览/搜索，选中时仍复制完整内容
M.thumbSize = 480 -- 图片缩略图最长边（点）
M.autoPaste = false -- 选中后是否自动按 ⌘V；false 时只复制到剪切板，手动粘贴
M.settingsKey = "clipboard.history"
M.width, M.height = 760, 460

-- 密码管理器等会标记这些类型，表示内容不应被记录（http://nspasteboard.org）
local ignoredTypes = {
  ["org.nspasteboard.ConcealedType"] = true,
  ["org.nspasteboard.TransientType"] = true,
  ["org.nspasteboard.AutoGeneratedType"] = true,
  ["com.agilebits.onepassword"] = true,
}

-- 每项：
--   { type = "text",  text = "...", time = n }
--   { type = "image", image = hs.image, thumb = "data:...", hash = "...", size = "w×h", time = n }
local history = {}
local nextId = 0 -- 每条分配稳定 id，面板通过 id 引用条目，避免后台新增条目导致下标错位
local watcher, webview, lastWindow, lastApp
local selfChangeCount -- 自己写入剪切板时的 changeCount，用于让 watcher 跳过
local refresh

---------------------------------------------------------------------------
-- History
---------------------------------------------------------------------------

local function newId()
  nextId = nextId + 1
  return nextId
end

local function findById(id)
  for i, item in ipairs(history) do
    if item.id == id then return i, item end
  end
end

local function save()
  local texts = {}
  for _, item in ipairs(history) do
    if item.type == "text" then
      table.insert(texts, { text = item.text, time = item.time })
    end
  end
  hs.settings.set(M.settingsKey, texts)
end

-- 清理过期条目，返回是否有变化
local function prune()
  if not M.maxAge then return false end
  local deadline = os.time() - M.maxAge
  local changed = false
  for i = #history, 1, -1 do
    if history[i].time < deadline then
      table.remove(history, i)
      changed = true
    end
  end
  return changed
end

local function load()
  history = {}
  local now = os.time()
  for _, entry in ipairs(hs.settings.get(M.settingsKey) or {}) do
    if type(entry) == "string" then -- 兼容旧格式（纯字符串数组）
      table.insert(history, { id = newId(), type = "text", text = entry, time = now })
    elseif type(entry) == "table" and entry.text then
      table.insert(history, { id = newId(), type = "text", text = entry.text, time = entry.time or now })
    end
  end
  if prune() then save() end
end

local function shouldIgnore()
  for _, t in ipairs(hs.pasteboard.pasteboardTypes() or {}) do
    if ignoredTypes[t] then
      return true
    end
  end
  return false
end

local function sameItem(a, b)
  if a.type ~= b.type then return false end
  if a.type == "text" then return a.text == b.text end
  return a.hash ~= nil and a.hash == b.hash
end

local function push(item)
  item.id = newId()
  for i, v in ipairs(history) do
    if sameItem(v, item) then
      table.remove(history, i)
      break
    end
  end
  table.insert(history, 1, item)

  -- 图片数量限制：从最旧的开始删
  if item.type == "image" then
    local images = 0
    for _, v in ipairs(history) do
      if v.type == "image" then images = images + 1 end
    end
    for i = #history, 1, -1 do
      if images <= M.maxImages then break end
      if history[i].type == "image" then
        table.remove(history, i)
        images = images - 1
      end
    end
  end

  while #history > M.maxItems do
    table.remove(history)
  end
  prune()
  save()
  refresh()
end

local function imageHash(image)
  local data = hs.pasteboard.readDataForUTI("public.png") or hs.pasteboard.readDataForUTI("public.tiff")
  return hs.hash.MD5(data or image:encodeAsURLString())
end

local function thumbnail(image)
  local s = image:size()
  local scale = math.min(1, M.thumbSize / math.max(s.w, s.h, 1))
  local w, h = math.max(1, math.floor(s.w * scale)), math.max(1, math.floor(s.h * scale))
  return image:copy():size({ w = w, h = h }, true):encodeAsURLString(true, "PNG")
end

local function onChange(contents)
  if selfChangeCount and hs.pasteboard.changeCount() == selfChangeCount then
    return -- 本模块自己写入的，history 已经排好序
  end
  if shouldIgnore() then
    return
  end
  if contents and contents:match("%S") then
    if #contents > M.maxTextSize then
      hs.alert.show(string.format("Clipboard content too large (%.0f KB), not saved", #contents / 1024), 1.5)
      return
    end
    push({ type = "text", text = contents, time = os.time() })
    return
  end
  local image = hs.pasteboard.readImage()
  if image then
    local s = image:size()
    push({
      type = "image",
      image = image,
      thumb = thumbnail(image),
      hash = imageHash(image),
      size = string.format("%d×%d", s.w, s.h),
      time = os.time(),
    })
  end
end

